/*!
 * Builds analytics/sample-summary.js from the deterministic synthetic events.
 * Run after changing the event schema or the dashboard:
 *   node analytics/tools/make-sample.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { generateSampleEvents } from "./generate.mjs";
import { buildComparison } from "../summary.js";

const now = Date.now();
const events = generateSampleEvents({ days: 60, now, seed: 20261116 });
const comparison = buildComparison(events, { days: 30, now });
const body = `/*!
 * Synthetic demo data for analytics/dashboard.html — generated by
 * analytics/tools/make-sample.mjs. Never contains real visitor data.
 * Regenerate: node analytics/tools/make-sample.mjs
 */
window.SAMPLE_SUMMARY = ${JSON.stringify(comparison)};
`;
const target = fileURLToPath(new URL("../sample-summary.js", import.meta.url));
writeFileSync(target, body);
console.log(`wrote ${target}: ${(body.length / 1024).toFixed(1)} KB, ${events.length} synthetic events, ${comparison.current.meta.session_count} sessions`);
